const CELL = 4; // px per dot pitch in viewBox units
const DOT = 3.2;

export function DotMatrix({
  text,
  label,
  className = '',
}: {
  text: string;
  label?: string;
  className?: string;
}) {
  const chars = [...text];
  const width = chars.length * 6 * CELL - CELL;
  const height = 7 * CELL;
  return (
    <svg
      className={`dot-matrix ${className}`}
      viewBox={`0 0 ${width} ${height}`}
      role="img"
      aria-label={label ?? text}
      preserveAspectRatio="xMinYMid meet"
    >
      {chars.map((ch, i) => {
        const rows = GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS[' '];
        return rows.map((row, y) =>
          [...row].map((bit, x) => (
            <rect
              key={`${i}-${y}-${x}`}
              x={(i * 6 + x) * CELL}
              y={y * CELL}
              width={DOT}
              height={DOT}
              rx={0.6}
              className={bit === '1' ? 'on' : 'off'}
            />
          )),
        );
      })}
    </svg>
  );
}
